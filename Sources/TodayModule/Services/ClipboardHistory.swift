import AppKit
import Combine
import ImageIO
import IslandCore

struct ClipItem: Identifiable, Equatable, Codable {
    enum Kind: String, Codable { case text, code, url, color, image, file }
    var id = UUID()
    var kind: Kind
    var text: String
    var source: String?
    var date: Date
    /// #RRGGBB для `color`.
    var colorHex: String?
    /// Только в памяти: исходные данные картинки (для «скопировать снова») / архив URL файлов.
    var imageData: Data?
    var imageType: String?
    /// Только в памяти: уменьшенное превью картинки (≤ 240 px), декодируется один раз при захвате.
    var thumbnail: NSImage?

    enum CodingKeys: String, CodingKey { case id, kind, text, source, date, colorHex }

    static func == (a: ClipItem, b: ClipItem) -> Bool { a.id == b.id && a.date == b.date }
}

/// Правила истории буфера (без AppKit-состояния — для самотеста).
enum ClipRules {
    static let maxItems = 20
    /// Картинки в истории: не больше `maxImages` штук и `maxImageBytes` исходных данных — старые выпадают.
    static let maxImages = 3
    static let maxImageBytes = 32_000_000
    static let maxSingleImageBytes = 16_000_000

    /// Пометки nspasteboard.org: пароли, временное, автосгенерированное — не записывать.
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]
    /// Менеджеры паролей: копирование из них не записывать, даже без пометки.
    static let skippedApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx", "com.bitwarden.desktop",
        "com.apple.Passwords", "com.apple.keychainaccess", "org.keepassxc.keepassxc", "com.lastpass.LastPass",
    ]

    static func shouldRecord(types: [String], frontmostBundle: String?) -> Bool {
        if types.contains(where: skippedTypes.contains) { return false }
        if let b = frontmostBundle, skippedApps.contains(b) { return false }
        return true
    }

    private static let colorRE = try! NSRegularExpression(pattern: #"^#?([0-9A-Fa-f]{6})$"#)
    private static let codeRE = try! NSRegularExpression(pattern: #"(\{|\}|;\s*$|\$\(|=>|->|\s--?[a-z]|^\s*(sudo|cd|git|swift|npm|brew|cat|ls|let|var|func|def|import)\s)"#,
                                                        options: [.anchorsMatchLines])

    /// Вид текста: цвет (#RRGGBB — показать образцом), ссылка, код (моноширинным), текст.
    static func classify(_ raw: String) -> (kind: ClipItem.Kind, colorHex: String?) {
        let s = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        let ns = s as NSString
        if let m = colorRE.firstMatch(in: s, range: NSRange(location: 0, length: ns.length)) {
            return (.color, "#" + ns.substring(with: m.range(at: 1)).uppercased())
        }
        if !s.contains(where: \.isWhitespace), let u = URL(string: s), let sch = u.scheme?.lowercased(),
           ["http", "https"].contains(sch), u.host != nil {
            return (.url, nil)
        }
        if codeRE.firstMatch(in: s, range: NSRange(location: 0, length: ns.length)) != nil { return (.code, nil) }
        return (.text, nil)
    }

    /// Похоже на токен/ключ — на диск не писать (длинное без пробелов, буквы вперемешку с цифрами).
    static func looksSecret(_ s: String) -> Bool {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard t.count >= 20, !t.contains(where: \.isWhitespace), !t.hasPrefix("http") else { return false }
        let digits = t.contains(where: \.isNumber), letters = t.contains(where: \.isLetter)
        return digits && letters
    }

    /// Добавить в начало: дубль текста поднимается наверх, хвост обрезается до `maxItems`.
    static func inserting(_ item: ClipItem, into list: [ClipItem]) -> [ClipItem] {
        var out = list.filter { !($0.kind != .image && $0.text == item.text && item.kind != .image) }
        out.insert(item, at: 0)
        if out.count > maxItems { out.removeLast(out.count - maxItems) }
        return trimmingImages(out)
    }

    /// Новые картинки важнее: идём сверху и выкидываем те, что не влезли в лимит штук/байт.
    static func trimmingImages(_ list: [ClipItem]) -> [ClipItem] {
        var count = 0, bytes = 0
        return list.filter { item in
            guard item.kind == .image else { return true }
            let size = item.imageData?.count ?? 0
            guard count < maxImages, bytes + size <= maxImageBytes else { return false }
            count += 1; bytes += size
            return true
        }
    }

    /// Превью через ImageIO (без декодирования в полный размер для JPEG/HEIC; PNG — один раз, в фоне).
    static func thumbnail(_ data: Data, maxPixels: Int = 240) -> CGImage? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let opts: [CFString: Any] = [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                     kCGImageSourceCreateThumbnailWithTransform: true,
                                     kCGImageSourceThumbnailMaxPixelSize: maxPixels]
        return CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary)
    }

    /// «2 мин», «1 ч», «вчера».
    static func age(_ d: Date, now: Date) -> String {
        let s = max(0, now.timeIntervalSince(d))
        if s < 60 { return "сейчас" }
        if s < 3600 { return "\(Int(s / 60)) мин" }
        if s < 86400 { return "\(Int(s / 3600)) ч" }
        return "\(Int(s / 86400)) дн"
    }
}

/// История буфера: опрос `changeCount` раз в секунду через общий тикер (`SharedTicker`: во сне, при выключенных
/// экранах, блокировке и в чужой сессии — пауза, после — один догоняющий тик). Событий у буфера нет; содержимое
/// читается только при смене счётчика. В памяти; на диск (0600) — только если включено «помнить между запусками».
/// Интервал — 1 с, а не 0,75 с: опрос идёт и в покое, а правила модулей (ARCHITECTURE.md) запрещают в покое чаще
/// раза в секунду; сетка 1 с склеивается с другими подписчиками тикера в одно пробуждение, 0,75 с — нет.
@MainActor
final class ClipboardHistory {
    static let pollInterval: TimeInterval = 1
    private(set) var items: [ClipItem] = []
    var onChange: (@MainActor ([ClipItem]) -> Void)?
    var persist = false { didSet { if persist { save() } else { removeFile() } } }

    private let pasteboard: NSPasteboard
    private var lastChange: Int
    private var tick: AnyCancellable?
    var isPolling: Bool { tick != nil }

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        self.lastChange = pasteboard.changeCount
    }

    static var file: URL {
        WeatherAPI.cacheFile.deletingLastPathComponent().appendingPathComponent("today-clipboard.json")
    }

    func start(persist: Bool) {
        if persist, items.isEmpty { load() }
        self.persist = persist
        lastChange = pasteboard.changeCount
        guard tick == nil else { return }
        tick = SharedTicker.shared.subscribe(every: Self.pollInterval) { [weak self] _ in self?.poll() }
    }

    func stop() { tick = nil }

    func poll() {
        let cc = pasteboard.changeCount
        guard cc != lastChange else { return }
        lastChange = cc
        capture()
    }

    private func capture() {
        let types = (pasteboard.types ?? []).map(\.rawValue)
        let front = NSWorkspace.shared.frontmostApplication
        guard !types.isEmpty, ClipRules.shouldRecord(types: types, frontmostBundle: front?.bundleIdentifier) else { return }
        let source = front?.localizedName
        var item: ClipItem?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let names = urls.map(\.lastPathComponent)
            item = ClipItem(kind: .file, text: names.count == 1 ? names[0] : "\(names[0]) и ещё \(names.count - 1)",
                            source: source, date: Date())
            item?.imageData = try? NSKeyedArchiver.archivedData(withRootObject: urls as NSArray, requiringSecureCoding: false)
        } else if let s = pasteboard.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let c = ClipRules.classify(s)
            item = ClipItem(kind: c.kind, text: String(s.prefix(2000)), source: source, date: Date(), colorHex: c.colorHex)
        } else if let t = [NSPasteboard.PasteboardType.png, .tiff].first(where: { types.contains($0.rawValue) }),
                  let data = pasteboard.data(forType: t), data.count < ClipRules.maxSingleImageBytes {
            item = ClipItem(kind: .image, text: "Изображение", source: source, date: Date(), imageData: data, imageType: t.rawValue)
        }
        guard let item else { return }
        items = ClipRules.inserting(item, into: items)
        onChange?(items)
        if persist { save() }
        if item.kind == .image, let data = item.imageData { makeThumbnail(id: item.id, data: data) }
    }

    private final class ImageBox: @unchecked Sendable { var image: CGImage? }

    /// Превью — в фоне, результат — на главный поток (карточка до этого показывает значок).
    private func makeThumbnail(id: UUID, data: Data) {
        let box = ImageBox()
        DispatchQueue.global(qos: .utility).async { [weak self] in
            box.image = ClipRules.thumbnail(data)
            DispatchQueue.main.async {
                MainActor.assumeIsolated {
                    guard let self, let cg = box.image, let i = self.items.firstIndex(where: { $0.id == id }) else { return }
                    self.items[i].thumbnail = NSImage(cgImage: cg, size: NSSize(width: cg.width / 2, height: cg.height / 2))
                    self.onChange?(self.items)
                }
            }
        }
    }

    /// Клик по карточке — вернуть в буфер (и поднять наверх; повторно не записывается).
    func copyBack(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .image:
            if let d = item.imageData, let t = item.imageType { pasteboard.setData(d, forType: NSPasteboard.PasteboardType(t)) }
        case .file:
            if let d = item.imageData,
               let urls = try? NSKeyedUnarchiver.unarchivedObject(ofClasses: [NSArray.self, NSURL.self], from: d) as? [URL] {
                pasteboard.writeObjects(urls as [NSURL])
            }
        default:
            pasteboard.setString(item.text, forType: .string)
        }
        lastChange = pasteboard.changeCount
        var moved = item
        moved.date = Date()
        items = ClipRules.inserting(moved, into: items.filter { $0.id != item.id })
        onChange?(items)
        if persist { save() }
    }

    func clear() {
        items = []
        onChange?(items)
        if persist { save() }
    }

    // MARK: Диск

    private func save() {
        let keep = items.filter { $0.kind != .image && $0.kind != .file && !ClipRules.looksSecret($0.text) }
        let enc = JSONEncoder(); enc.dateEncodingStrategy = .secondsSince1970
        guard let d = try? enc.encode(keep) else { return }
        Self.writePrivately(d, to: Self.file)
    }

    /// Запись без окна с правами по umask: временный файл сразу создаётся 0600 (O_EXCL), затем rename.
    @discardableResult
    static func writePrivately(_ data: Data, to url: URL) -> Bool {
        let dir = url.deletingLastPathComponent()
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        let tmp = dir.appendingPathComponent(".\(url.lastPathComponent).\(getpid()).\(UUID().uuidString.prefix(8)).tmp")
        let fd = open(tmp.path, O_WRONLY | O_CREAT | O_EXCL | O_CLOEXEC, 0o600)
        guard fd >= 0 else { return false }
        var ok = data.withUnsafeBytes { buf -> Bool in
            var off = 0
            while off < buf.count {
                let n = write(fd, buf.baseAddress! + off, buf.count - off)
                if n <= 0 { return false }
                off += n
            }
            return true
        }
        ok = close(fd) == 0 && ok
        if ok, rename(tmp.path, url.path) == 0 { return true }
        unlink(tmp.path)
        return false
    }

    private func load() {
        let dec = JSONDecoder(); dec.dateDecodingStrategy = .secondsSince1970
        guard let d = try? Data(contentsOf: Self.file), let list = try? dec.decode([ClipItem].self, from: d) else { return }
        items = Array(list.prefix(ClipRules.maxItems))
        onChange?(items)
    }

    private func removeFile() { try? FileManager.default.removeItem(at: Self.file) }
}
